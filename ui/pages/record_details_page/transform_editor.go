const (
	// attachedShown is how many attached files are listed, the others are counted
	attachedShown = 3
	// editorChrome is the number of lines the dialog takes besides the filter field
	editorChrome = 18
	// previewDelay is how long the filter must stay unchanged before its result is computed
	previewDelay = 200 * time.Millisecond
)

// transformEditor edits the jq filter that transforms the records decoded by one rule.
// The result of the filter on the shown record is displayed while typing. The filter can
// also be generated by a language model from a description and attached files.
type transformEditor struct {
	payload     string
	description string
	// attachments are the files included in the prompt of the LLM
	attachments []string
	// files chooses an attachment, nil while not choosing
	files  *filepicker.Model
	filter string
	// filterText is the field of the filter, its height adapts to the window
	filterText *huh.Text
	// descInput is the field describing the transformation for the LLM
	descInput *huh.Input
	// generated is the filter the language model returned last, saved as such if unchanged
	generated  string
	generating bool
	status     string
	form       *huh.Form
	// picker chooses the LLM tool when none is configured, nil otherwise
	picker *toolPicker

	// previewOut and previewErr are the result of the filter, computed by computePreview so that
	// rendering never runs the filter
	previewOut  string
	previewText string
	previewErr  error
	// previewSeq identifies the latest filter change, a delayed computation is only run if it
	// still matches
	previewSeq int
}

// previewDueMsg asks to compute the result of the filter, sent previewDelay after a change.
type previewDueMsg struct {
	seq int
}

// toolPicker lets the user choose the LLM tool, or enter a custom command.
type toolPicker struct {
	cursor int
	custom bool
	input  textinput.Model
}

// llmGeneratedMsg is the result of generating a filter with the LLM.
type llmGeneratedMsg struct {
	filter string
	err    error
}

func newTransformEditor(payload, filter string) *transformEditor {
	e := &transformEditor{payload: payload, filter: filter}
	e.buildForm()
	e.computePreview()
	return e
}

// buildForm creates the form on the current values, the fields write into them. tab moves
// between the description and the filter.
func (e *transformEditor) buildForm() {
	// enter inserts a new line into the filter, the filter is saved with ctrl+s
	keys := huh.NewDefaultKeyMap()
	keys.Text.Submit = key.NewBinding(key.WithKeys())
	keys.Text.Next = key.NewBinding(key.WithKeys())
	keys.Text.NewLine = key.NewBinding(key.WithKeys("enter", "alt+enter", "ctrl+j"), key.WithHelp("enter", "new line"))

	e.filterText = huh.NewText().
		Value(&e.filter).
		Title("Transformation (jq filter)").
		ShowLineNumbers(true)
	e.filterText.WithKeyMap(keys)

	e.descInput = huh.NewInput().
		Value(&e.description).
		Title("Describe the transformation (ctrl+g generates it)")
	fields := []huh.Field{
		e.descInput,
		e.filterText,
	}
	e.form = huh.NewForm(huh.NewGroup(fields...)).WithTheme(styles.Huh).WithShowHelp(false)
	e.form.Init()
}

// computePreview applies the filter to the payload and keeps the result for rendering. The result
// is formatted here, rendering only lays out the lines that are shown.
func (e *transformEditor) computePreview() {
	e.previewOut, e.previewErr = transformation.Transform(strings.TrimSpace(e.filter), e.payload)
	e.previewText = ""
	if e.previewErr == nil {
		e.previewText = ui.FormatPayload(e.previewOut)
	}
}

// update passes the message to the form. A changed filter computes its result after a delay,
// so that a burst of key presses runs the filter once.
func (e *transformEditor) update(msg tea.Msg) tea.Cmd {
	before := e.filter
	form, cmd := e.form.Update(msg)
	if f, ok := form.(*huh.Form); ok {
		e.form = f
	}
	if e.filter == before {
		return cmd
	}
	e.previewSeq++
	seq := e.previewSeq
	return tea.Batch(cmd, tea.Tick(previewDelay, func(time.Time) tea.Msg {
		return previewDueMsg{seq: seq}
	}))
}

// handlePreviewDue computes the result unless the filter changed again since the message was sent.
func (e *transformEditor) handlePreviewDue(msg previewDueMsg) {
	if msg.seq == e.previewSeq {
		e.computePreview()
	}
}

// setFilter replaces the filter, the form is rebuilt because it does not follow the value.
func (e *transformEditor) setFilter(filter string) {
	e.filter = filter
	e.previewSeq++
	e.buildForm()
	e.computePreview()
}

// attach adds the file unless it is attached already.
func (e *transformEditor) attach(path string) {
	for _, a := range e.attachments {
		if a == path {
			return
		}
	}
	e.attachments = append(e.attachments, path)
}

// openFilePicker starts choosing a file, in the directory of the last attachment if there is one.
func (e *transformEditor) openFilePicker() {
	start := ""
	if n := len(e.attachments); n > 0 {
		start = filepath.Dir(e.attachments[n-1])
	}
	e.files = filepicker.New(start)
}

// detachLast removes the most recently attached file.
func (e *transformEditor) detachLast() {
	if n := len(e.attachments); n > 0 {
		e.attachments = e.attachments[:n-1]
	}
}

// View renders the dialog within the given width and height: the editing fields on the left,
// the result of the filter on the right.
func (e *transformEditor) View(windowWidth, maxHeight int) string {
	width := max(40, windowWidth-4)
	maxHeight = max(12, maxHeight)

	if e.picker != nil {
		return clipLines(styles.Help.Modal.Render(lg.JoinVertical(lg.Left, e.picker.view(width)...)), maxHeight)
	}
	if e.files != nil {
		return clipLines(styles.Help.Modal.Render(lg.JoinVertical(lg.Left,
			styles.Help.Title.Render("Attach a file"),
			"",
			e.files.View(width),
			"",
			styles.Help.Footer.Width(width).Render("↑↓ move · enter choose · ← up · type to filter · esc close"),
		)), maxHeight)
	}

	// the filter field takes the lines left over, until the dialog fits the height
	filterHeight := max(3, maxHeight-editorChrome)
	for {
		e.filterText.WithHeight(filterHeight)
		view := e.render(width, maxHeight)
		over := lg.Height(view) - maxHeight
		if over <= 0 || filterHeight <= 3 {
			return clipLines(view, maxHeight)
		}
		filterHeight = max(3, filterHeight-over)
	}
}

// render lays out the dialog with the filter field at its current height.
func (e *transformEditor) render(width, maxHeight int) string {
	leftWidth := width * 2 / 5
	rightWidth := width - leftWidth - 3

	e.form.WithWidth(leftWidth)
	// the fields take the width of the left column themselves, the form sizes them differently
	e.descInput.WithWidth(leftWidth)
	e.filterText.WithWidth(leftWidth)
	left := []string{e.form.View()}
	if len(e.attachments) > 0 {
		left = append(left, "", styles.Help.Key.Render("Attached"))
		shown := e.attachments
		if len(shown) > attachedShown {
			shown = shown[len(shown)-attachedShown:]
		}
		if more := len(e.attachments) - len(shown); more > 0 {
			left = append(left, styles.Help.Footer.Render("  … "+strconv.Itoa(more)+" more"))
		}
		for _, a := range shown {
			left = append(left, lg.NewStyle().Width(leftWidth).Render("  "+a))
		}
	}
	if e.status != "" {
		left = append(left, "", lg.NewStyle().Width(leftWidth).Render(e.status))
	}

	var result string
	switch {
	case e.generating:
		result = "⏳ Generating the transformation …"
	default:
		if e.previewErr != nil {
			result = styles.Notifier.Error.UnsetMarginLeft().Render(e.previewErr.Error())
		} else {
			result = e.previewText
		}
	}
	// only the visible lines are wrapped, the full result is in the record view
	limit := max(3, maxHeight-editorChrome)
	resultLines := visibleLines(result, rightWidth, limit)
	if len(resultLines) > limit {
		resultLines = append(resultLines[:limit-1], styles.Help.Footer.Render("… truncated"))
	}
	right := []string{styles.Help.Key.Render("Result"), strings.Join(resultLines, "\n")}

	columns := lg.JoinHorizontal(lg.Top,
		lg.NewStyle().Width(leftWidth).Render(lg.JoinVertical(lg.Left, left...)),
		"   ",
		lg.NewStyle().Width(rightWidth).Render(lg.JoinVertical(lg.Left, right...)),
	)
	return styles.Help.Modal.Render(lg.JoinVertical(lg.Left,
		styles.Help.Title.Render("Transform records"),
		"",
		columns,
		"",
		styles.Help.Footer.Width(width).Render("ctrl+s save · ctrl+g generate · ctrl+o attach file · ctrl+r remove last file · esc cancel"),
	))
}

// clipLines cuts the view to at most height lines.
func clipLines(view string, height int) string {
	return lg.NewStyle().MaxHeight(height).Render(view)
}

// visibleLines wraps the text to the width line by line and stops once there are more than
// limit lines, so that a long result is not wrapped in full on every frame.
func visibleLines(text string, width, limit int) []string {
	var lines []string
	for _, raw := range strings.Split(text, "\n") {
		for _, line := range strings.Split(lg.NewStyle().Width(width).Render(raw), "\n") {
			lines = append(lines, line)
			if len(lines) > limit {
				return lines
			}
		}
	}
	return lines
}

func (e *transformEditor) Shortcuts() []statusbar.Shortcut {
	if e.files != nil {
		return []statusbar.Shortcut{
			{Name: "Choose", Keybinding: "enter"},
			{Name: "Back", Keybinding: "esc"},
		}
	}
	if e.picker != nil {
		return []statusbar.Shortcut{
			{Name: "Choose", Keybinding: "enter"},
			{Name: "Back", Keybinding: "esc"},
		}
	}
	return []statusbar.Shortcut{
		{Name: "Save", Keybinding: "C-s"},
		{Name: "Generate", Keybinding: "C-g"},
		{Name: "Attach File", Keybinding: "C-o"},
		{Name: "Close", Keybinding: "esc"},
	}
}

// transformEditorFilter is the filter shown when editing, the saved one or the identity filter.
func transformEditorFilter(saved []transformation.Entry) string {
	if len(saved) == 0 {
		return "."
	}
	return saved[len(saved)-1].Filter
}

// pickerOptions are the presets followed by the custom command.
func pickerOptions() []string {
	var options []string
	for _, p := range config.LLMPresets {
		options = append(options, p.Name+"  ("+strings.Join(p.Config.Command, " ")+")")
	}
	return append(options, "Custom command")
}

func newToolPicker() *toolPicker {
	input := textinput.New()
	input.Placeholder = "command and arguments, the prompt is read from stdin"
	input.Focus()
	return &toolPicker{input: input}
}

func (p *toolPicker) view(width int) []string {
	parts := []string{styles.Help.Title.Render("Choose the LLM tool"), ""}
	if p.custom {
		p.input.SetWidth(width)
		parts = append(parts, styles.Help.Key.Render("Custom command"), p.input.View())
		parts = append(parts, "", styles.Help.Footer.Width(width).Render("enter save · esc back"))
		return parts
	}
	for i, option := range pickerOptions() {
		line := "  " + option
		if i == p.cursor {
			line = "> " + option
		}
		parts = append(parts, lg.NewStyle().Width(width).Render(line))
	}
	parts = append(parts, "", styles.Help.Footer.Width(width).Render("↑↓ move · enter choose · esc close"))
	return parts
}
